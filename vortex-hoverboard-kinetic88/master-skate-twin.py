import math

class HoverboardSymmetricalTwin:
    def __init__(self):
        # 🪐 UNIVERSAL NATURAL CONSTANTS & REFINED ATMOSPHERIC BASES
        self.GOLDEN_RATIO_PHI = 1.61803398875   # Perfect scale-invariant geometric factor
        self.GRAVITY_ACCEL_MS2 = 9.80665        # Standard planetary gravity baseline (m/s^2)
        self.WATER_MASS_DENSITY_KG_M3 = 1000.0  # Constant density of closed loop liquid fluid
        
        # 📐 PERSONAL HOVERBOARD MACHINE SPECIFICATIONS (DECK SCALE)
        self.DECK_CURB_MASS_KG = 10.0           # 8.2kg printed frame + 1.8kg liquid fluid loop
        self.MAX_RIDER_PAYLOAD_KG = 100.0       # Maximum rated human pilot weight limits
        self.LIFT_CELL_RADIUS_METERS = 0.11     # Fixed dual cell radius for foot deck scale
        self.CRITICAL_IGNITION_RPM = 12500.0    # Threshold velocity for self-sustaining vortex
        self.TOTAL_CELL_COUNT = 2               # Symmetrical dual pad layout (Front/Rear)
        
        # 🛡️ HARDENING & AUXILIARY METRICS
        self.EMP_ISOLATION_FLOOR_DB = 140.0     # Absolute spectrum shielding attenuation
        self.HARMONIC_RIPPLE_FREQUENCY_HZ = 2400.0 # Standing wave frequency line

    def calculate_skate_physics(self, core_rpm: float, rider_weight_kg: float):
        """
        Calculates centripetal fluid velocity, induced internal vacuum depth,
        required ground-effect lift forces, and remaining vertical thrust margins.
        """
        # Constrain variables to realistic cleanroom operational windows
        current_rpm = max(100.0, min(35000.0, core_rpm))
        current_rider_mass = max(0.0, min(150.0, rider_weight_kg))
        
        # Total flying mass profiles
        total_flying_mass_kg = self.DECK_CURB_MASS_KG + current_rider_mass
        required_lift_newtons = total_flying_mass_kg * self.GRAVITY_ACCEL_MS2
        
        # 1. CENTRIPETAL FLUID ACCELERATION ALONG THE GOLDEN SPIRAL GROOVES
        # Tangential disc tip speed mapping
        disc_angular_velocity_rad_s = (current_rpm * 2.0 * math.pi) / 60.0
        disc_tip_velocity_ms = disc_angular_velocity_rad_s * self.LIFT_CELL_RADIUS_METERS
        
        # Centripetal inward acceleration multiplier driven by the 1:1.618 golden geometry
        centripetal_velocity_multiplier = self.GOLDEN_RATIO_PHI * 2.0
        core_vortex_fluid_velocity_ms = disc_tip_velocity_ms * centripetal_velocity_multiplier
        
        # 2. ISOTHERMAL VACUUM DELTA LIFT GENERATION
        # Localized pressure drop over the central axis (Bernoulli Pressure Delta)
        # For water: Delta P = 0.5 * density * V_core^2 (Internal loop potential scale)
        induced_internal_delta_pa = 0.5 * self.WATER_MASS_DENSITY_KG_M3 * (core_vortex_fluid_velocity_ms ** 2)
        
        # Total available atmospheric pressure ceiling on Earth (101,325 Pa)
        # The lift force is generated by the atmospheric pressure pushing up against the vacuum cell area
        max_vacuum_ceiling_pa = 101325.0
        effective_vacuum_pa = min(max_vacuum_ceiling_pa, induced_internal_delta_pa * 0.001) # Scaled down to airframe translation
        effective_vacuum_kpa = -effective_vacuum_pa / 1000.0
        
        # Total effective lifting surface area across both dual cells
        single_cell_area_m2 = math.pi * (self.LIFT_CELL_RADIUS_METERS ** 2)
        total_lift_area_m2 = single_cell_area_m2 * self.TOTAL_CELL_COUNT * self.GOLDEN_RATIO_PHI
        
        generated_aerodynamic_lift_newtons = effective_vacuum_pa * total_lift_area_m2
        lift_margin_newtons = generated_aerodynamic_lift_newtons - required_lift_newtons
        
        # Calculate target hover height footprint based on ground effect compression
        if current_rpm >= self.CRITICAL_IGNITION_RPM and lift_margin_newtons >= 0:
            hover_height_mm = 75.0 + (lift_margin_newtons * 0.02)
            hover_height_mm = min(120.0, hover_height_mm)
            machine_status = "ACTIVE_ALL_TERRAIN_HOVER"
        else:
            hover_height_mm = 0.0
            machine_status = "INSUFFICIENT_VORTEX_VACUUM_SPEED"
            
        return {
            "disc_tip_velocity_ms": round(disc_tip_velocity_ms, 2),
            "core_vortex_fluid_speed_ms": round(core_vortex_fluid_velocity_ms, 2),
            "induced_vacuum_kpa": round(effective_vacuum_kpa, 2),
            "required_lift_force_n": round(required_lift_newtons, 2),
            "generated_total_lift_n": round(generated_aerodynamic_lift_newtons, 2),
            "net_lift_margin_n": round(lift_margin_newtons, 2),
            "calculated_hover_height_mm": round(hover_height_mm, 1),
            "machine_operational_code": machine_status
        }

